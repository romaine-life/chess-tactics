export const RUN_UNIT_NAME_CAPACITY_BY_ROLE: Readonly<Record<HistoricalRunNameRole, number>> = Object.freeze(
  Object.fromEntries(
    Object.entries(HISTORICAL_RUN_UNIT_NAMES).map(([role, names]) => [role, names.length]),
  ) as Record<HistoricalRunNameRole, number>,
);

export const RUN_UNIT_NAME_MINIMUM_CAPACITY = Math.min(...Object.values(RUN_UNIT_NAME_CAPACITY_BY_ROLE));

function nameSeed(seed: number, role: HistoricalRunNameRole): number {
  let value = seed >>> 0;
  for (let index = 0; index < role.length; index += 1) {
    value ^= role.charCodeAt(index);
    value = Math.imul(value, 16777619) >>> 0;
  }
  value ^= value >>> 16;
  value = Math.imul(value, 0x7feb352d) >>> 0;
  value ^= value >>> 15;
  value = Math.imul(value, 0x846ca68b) >>> 0;
  return (value ^ (value >>> 16)) >>> 0;
}

function shuffledNames<T>(values: readonly T[], seed: number): T[] {
  const result = [...values];
  const rng = createRng(seed);
  for (let index = result.length - 1; index > 0; index -= 1) {
    const other = rng.int(index + 1);
    [result[index], result[other]] = [result[other], result[index]];
  }
  return result;
}

/**
 * Returns one stable, role-appropriate historical identity. `roleOrdinal`
 * counts acquisitions of this piece type, so a role does not repeat a name
 * until its complete pool has been used.
 */
export function runUnitName(
  seed: number,
  role: HistoricalRunNameRole,
  roleOrdinal: number,
): string {
  const names = HISTORICAL_RUN_UNIT_NAMES[role];
  const ordinal = Math.max(0, Math.trunc(roleOrdinal)) % names.length;
  return shuffledNames(names, nameSeed(seed, role))[ordinal];
}
